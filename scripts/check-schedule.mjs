import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { ensureKeynote, scheduleLocation, symposiumVenue } from '../src/schedule-details.ts';

assert.equal(scheduleLocation('Forum'), 'Grainger');
assert.equal(scheduleLocation('Forum/Online'), 'Grainger/Online');
assert.equal(scheduleLocation('New Dining Hall'), 'Grainger');
assert.equal(scheduleLocation('New Dining Hall/Online'), 'Grainger/Online');
assert.equal(scheduleLocation('Grainger/Online'), 'Grainger/Online');
assert.equal(scheduleLocation('Phelps Lobby/Online'), 'Phelps Lobby/Online');
assert.equal(symposiumVenue, 'Phillips Exeter Academy — Phelps Lobby and Grainger.');
const openingRows = ensureKeynote([{ time: '9:00 AM', event: 'Opening Ceremony', location: 'Grainger' }]);
assert.deepEqual(openingRows.slice(0, 3).map(row => row.event), ['Symposium Orientation & Logistics', 'Faculty Welcome Address', 'Opening Keynote Presentation']);
assert.deepEqual(openingRows.slice(0, 3).map(row => row.time), ['9:00 – 9:10 AM', '9:10 – 9:15 AM', '9:15 – 10:15 AM']);
assert.equal(ensureKeynote([{ time: '12:30 PM', event: 'Keynote Presentation', location: 'Grainger' }]).length, 1);
const page = readFileSync(new URL('../src/pages/schedule.tsx', import.meta.url), 'utf8');
assert(!/Forum|New Dining Hall/.test(page));
assert(page.includes('{symposiumVenue}'));
assert(page.includes('{"Symposium Orientation & Logistics"}'));
assert(page.includes('{"Faculty Welcome Address"}'));
assert(page.includes('{"Opening Keynote Presentation"}'));
console.log('Schedule locations and venue summary passed.');
