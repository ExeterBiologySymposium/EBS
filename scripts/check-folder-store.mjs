import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { createServer } from 'vite';
const vite = await createServer({ server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
const db = new PGlite();
try {
  const { createFolderStore } = await vite.ssrLoadModule('/server/drive/store.ts');
  await db.exec(await readFile(new URL('./sql/participant-folders.sql', import.meta.url), 'utf8'));
  const query = async (text, params) => (await db.query(text, params)).rows;
  const store = createFolderStore(query, 'development:parent:template');
  const other = createFolderStore(query, 'production:parent:template');
  await Promise.all(Array.from({ length: 6 }, (_, i) => store.ensure('self', 'student@example.com', 'folder-' + i)));
  const row = await store.get('self');
  assert(row.folderId.startsWith('folder-'));
  assert.equal(row.documentId, null);
  assert.equal(row.ready, false);
  assert.equal(await other.get('self'), null, 'namespaces must isolate environments');
  const claims = await Promise.all(Array.from({ length: 6 }, () => store.claim('self')));
  assert.equal(claims.filter(Boolean).length, 1);
  const claim = claims.find(Boolean);
  assert.equal(await store.startCopy('self', 'wrong-token'), false);
  assert.equal(await store.startCopy('self', claim), true);
  assert.equal(await store.startCopy('self', claim), false);
  await store.release('self', 'wrong-token');
  assert.equal(await store.claim('self'), null, 'wrong owner cannot release claim');
  await assert.rejects(store.document('self', 'wrong-token', 'doc'));
  await db.query("UPDATE ebs_participant_folders SET claim_until=now()-interval '1 second' WHERE user_id=$1", ['self']);
  await assert.rejects(store.document('self', claim, 'doc'), /claim lost/);
  const replacement = await store.claim('self');
  assert(replacement);
  assert.notEqual(replacement, claim);
  assert.equal(await store.startCopy('self', replacement), false, 'expiry must not allow a second Docs copy');
  await assert.rejects(store.complete('self', replacement), /claim lost/);
  await store.document('self', replacement, 'doc');
  await store.complete('self', replacement);
  await store.release('self', replacement);
  assert.equal((await store.get('self')).ready, true);
  assert.equal((await store.get('self')).documentId, 'doc');
  assert.equal(await store.claim('self'), null);
  await store.ensure("user'; DROP TABLE ebs_participant_folders; --", 'other@example.com', 'other-folder');
  assert.equal((await store.get('self')).ready, true, 'queries must bind parameters');
  console.log('PASS: actual PostgreSQL schema, concurrent unique mapping and claims, lease expiry, fencing, permanent copy intent, environment isolation, and parameter binding.');
} finally { await db.close(); await vite.close(); }
